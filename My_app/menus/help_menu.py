import wx


def create(parent):
    helpMenu = wx.Menu()

    helpId = wx.NewIdRef()
    parent.Bind(wx.EVT_MENU, lambda e: show_help(parent), id=helpId)
    helpMenu.Append(helpId, "&View Help\tF1", "View application help")

    return helpMenu


